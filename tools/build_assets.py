# Build game assets from the 1nc0gn30 toolkit + agents v2 sheets -> assets/*.png and src/assets.js (data URIs)
import json, base64, io, os, colorsys
import numpy as np
from PIL import Image
R='/workspace/1nc0gn30'; OUT='assets'
os.makedirs(OUT+'/agents',exist_ok=True)
PANTH=json.load(open(R+'/episodes/ep07/src/pantheon.json'))
TARGET={'ignis':(249,115,22),'radical-minion':(217,70,239),'draco':(245,158,11)}
def remap(a,dst):
    rgb=a[...,:3].astype(float)/255; r,g,b=rgb[...,0],rgb[...,1],rgb[...,2]
    mx=rgb.max(-1); mn=rgb.min(-1); s=np.where(mx>0,(mx-mn)/np.maximum(mx,1e-6),0)
    red=(r==mx)&(s>0.45)&(r>0.25)&((g-b)<0.18)&((g/np.maximum(r,1e-6))<0.62)&(a[...,3]>0)
    d=np.array(dst,float)/255; v=mx[red][:,None]/ (max(d)) 
    out=np.clip(d[None,:]*v*1.0,0,1)
    # keep highlights (whitish) mixing
    a2=a.copy(); a2[...,:3][red]=(out*255).astype(np.uint8); return a2, int(red.sum())
meta=[]; data={}
def uri(path):
    return 'data:image/png;base64,'+base64.b64encode(open(path,'rb').read()).decode()
for p in PANTH:
    n=p['id'].lower()
    if n=='azoth': continue   # stays unnamed / not in game
    a=np.array(Image.open(f'{R}/episodes/agents-v2/{n}_spritesheet_v2.png').convert('RGBA'))
    cnt=0
    if n in TARGET: a,cnt=remap(a,TARGET[n])
    Image.fromarray(a).save(f'{OUT}/agents/{n}.png',optimize=True)
    al=a[0:96,0:96,3]>0; foot=int(np.nonzero(al.any(1))[0].max()); top=int(np.nonzero(al.any(1))[0].min())
    col=p['color'] if n not in TARGET else '#%02X%02X%02X'%TARGET[n]
    meta.append(dict(id=n,name=p['name'],color=col,sec=p['secondaryColor'],role=p['role'],ability=p['ability'],foot=foot,top=top,remapped=cnt))
    data['ag_'+n]=uri(f'{OUT}/agents/{n}.png')
for f in ['walk','side','front','back','dissolve','mini','font']:
    Image.open(f'{R}/toolkit/assets/{f}.png').save(f'{OUT}/{f}.png'); data[f]=uri(f'{OUT}/{f}.png')
for f in ['sleep','kneel','lie']:
    im=Image.open(f'{R}/toolkit/sprites/{f}.png').convert('RGBA'); im.save(f'{OUT}/{f}.png'); data[f]=uri(f'{OUT}/{f}.png')
font=json.load(open(f'{R}/toolkit/assets/font.json'))
sp=json.load(open(f'{R}/toolkit/assets/sprites.json'))
with open('src/assets.js','w') as fh:
    fh.write('// generated by tools/build_assets.py\n')
    fh.write('export const IMG='+json.dumps(data)+';\n')
    fh.write('export const FONT='+json.dumps(font)+';\n')
    fh.write('export const SHEETS='+json.dumps(sp)+';\n')
    fh.write('export const AGENTS='+json.dumps(meta,indent=0)+';\n')
for m in meta: print(m['id'],m['color'],m['foot'],m['top'],m['remapped'])
print(os.path.getsize('src/assets.js'))
